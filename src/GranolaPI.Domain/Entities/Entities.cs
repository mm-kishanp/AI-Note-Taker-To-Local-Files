using GranolaPI.Domain.Enums;

namespace GranolaPI.Domain.Entities;

public class Client
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public string Name { get; set; } = "";
    public string? Description { get; set; }
    public DateTime CreatedAt { get; set; } = DateTime.UtcNow;
    public DateTime UpdatedAt { get; set; } = DateTime.UtcNow;

    public List<Project> Projects { get; set; } = [];
    public List<ClassificationRule> Rules { get; set; } = [];
}

public class Project
{
    /// <summary>Stable internal ID. Never derived from the display name.</summary>
    public Guid Id { get; set; } = Guid.NewGuid();
    public string Name { get; set; } = "";
    /// <summary>Folder-safe identifier used in directory templates. Unique.</summary>
    public string Slug { get; set; } = "";
    public string? Description { get; set; }
    public Guid? ClientId { get; set; }
    public Client? Client { get; set; }
    public ProjectStatus Status { get; set; } = ProjectStatus.Active;
    /// <summary>Optional override, relative to the notes root. Null uses the configured template.</summary>
    public string? NotesFolderPath { get; set; }
    /// <summary>Optional override, relative to the transcripts root. Null uses the configured template.</summary>
    public string? TranscriptFolderPath { get; set; }
    /// <summary>Lower value wins ties between otherwise equal candidates in multi-export mode.</summary>
    public int DefaultClassificationPriority { get; set; } = 100;
    public DateTime CreatedAt { get; set; } = DateTime.UtcNow;
    public DateTime UpdatedAt { get; set; } = DateTime.UtcNow;

    public List<ClassificationRule> Rules { get; set; } = [];
}

/// <summary>
/// A single mapping used by the classification engine: participant emails, email domains,
/// participant names, verified speaker names, Granola folders and keywords. Belongs to a project
/// or to a client (client rules produce candidate projects).
/// </summary>
public class ClassificationRule
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public Guid? ProjectId { get; set; }
    public Project? Project { get; set; }
    public Guid? ClientId { get; set; }
    public Client? Client { get; set; }
    public RuleKind Kind { get; set; }
    public string Value { get; set; } = "";
    public string NormalizedValue { get; set; } = "";
    public bool Enabled { get; set; } = true;
    public DateTime CreatedAt { get; set; } = DateTime.UtcNow;
}

public class Meeting
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public string GranolaNoteId { get; set; } = "";
    public string Title { get; set; } = "";
    public DateTime CreatedAt { get; set; }
    public DateTime UpdatedAt { get; set; }
    public DateTime? MeetingStartTime { get; set; }
    public DateTime? MeetingEndTime { get; set; }
    public string? OwnerName { get; set; }
    public string? OwnerEmail { get; set; }
    public string AttendeesJson { get; set; } = "[]";
    public string ParticipantEmailsJson { get; set; } = "[]";
    public string SpeakerMetadataJson { get; set; } = "[]";
    public string CalendarEventJson { get; set; } = "null";
    public string SourceFoldersJson { get; set; } = "[]";
    public string AttachmentsJson { get; set; } = "[]";
    /// <summary>Granola's summary (markdown). Generated by Granola, stored verbatim.</summary>
    public string? Summary { get; set; }
    /// <summary>The owner's own notes (markdown), when the API key permits.</summary>
    public string? NotesContent { get; set; }
    /// <summary>Structured transcript segments as returned by the API (JSON array).</summary>
    public string? TranscriptContent { get; set; }
    public int TranscriptSegmentCount { get; set; }
    public string? SourceUrl { get; set; }
    public string? SourceFolderId { get; set; }

    public ContentStatus NotesStatus { get; set; }
    public ContentStatus TranscriptStatus { get; set; }
    public SourceStatus SourceStatus { get; set; }

    public Guid? AssignedProjectId { get; set; }
    public Project? AssignedProject { get; set; }
    public ClassificationStatus ClassificationStatus { get; set; }
    public AssignmentMethod AssignmentMethod { get; set; }
    public Certainty Certainty { get; set; }
    public string? ClassificationReason { get; set; }
    /// <summary>JSON: the full explanation (rule, evidence, candidates, conflicts).</summary>
    public string ClassificationDetailJson { get; set; } = "null";
    public bool NeedsReview { get; set; }

    public ManualAssignmentKind ManualAssignment { get; set; }
    public Guid? ManualProjectId { get; set; }
    public DateTime? ManualAssignedAt { get; set; }

    /// <summary>Aggregate export status of the meeting (worst of its export records).</summary>
    public ExportStatus ExportStatus { get; set; }
    public bool ExportPending { get; set; } = true;
    public string? NotesExportPath { get; set; }
    public string? TranscriptExportPath { get; set; }

    public string? SourceContentHash { get; set; }
    public DateTime? LastSuccessfulFetchAt { get; set; }
    public DateTime? LastSuccessfulExportAt { get; set; }
    public string? LastSyncError { get; set; }
    public ErrorCategory LastErrorCategory { get; set; }
    public int FailureCount { get; set; }
    public DateTime? NextRetryAt { get; set; }

    public DateTime CreatedLocallyAt { get; set; } = DateTime.UtcNow;
    public DateTime UpdatedLocallyAt { get; set; } = DateTime.UtcNow;

    public List<MeetingParticipant> Participants { get; set; } = [];
    public List<MeetingProjectAssignment> ProjectAssignments { get; set; } = [];
    public List<ExportRecord> ExportRecords { get; set; } = [];
}

public class MeetingParticipant
