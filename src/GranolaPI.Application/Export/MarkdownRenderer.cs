public sealed record MeetingDocument
{
    public MeetingSource Source { get; init; } = MeetingSource.Granola;
    public string GranolaNoteId { get; init; } = "";
    public string Title { get; init; } = "";
    public DateTimeOffset MeetingDate { get; init; }
    public DateTimeOffset? MeetingStart { get; init; }
    public DateTimeOffset? MeetingEnd { get; init; }
    public DateTimeOffset CreatedAt { get; init; }
    public DateTimeOffset UpdatedAt { get; init; }
    public string? OwnerName { get; init; }
    public string? OwnerEmail { get; init; }
    public IReadOnlyList<ParticipantFact> Attendees { get; init; } = [];
    public string? CalendarTitle { get; init; }
    public string? SummaryMarkdown { get; init; }
    public string? NotesMarkdown { get; init; }
    public IReadOnlyList<GranolaTranscriptSegment> Transcript { get; init; } = [];
    public IReadOnlyList<GranolaAttachment> Attachments { get; init; } = [];
    public string? SourceUrl { get; init; }
    public string? ProjectName { get; init; }
    public string? ProjectSlug { get; init; }
    public Guid? ProjectId { get; init; }
    public string? ClientName { get; init; }
    public ClassificationStatus ClassificationStatus { get; init; }
    public AssignmentMethod ClassificationMethod { get; init; }
    public string? ClassificationRule { get; init; }
    public ExportLocation Location { get; init; }
    public ExportRole Role { get; init; }
    public string? CanonicalProject { get; init; }
    public string? NotesLink { get; init; }
    public string? TranscriptLink { get; init; }
    public bool IncludeAttachmentLinks { get; init; } = true;
}

/// <summary>
/// Renders notes and transcript Markdown. Output is deterministic for the same input (apart from
/// <c>generated_at</c>), and carries a <c>content_hash</c> so user edits can be detected later
/// even without the database.
/// </summary>
public static partial class MarkdownRenderer
{
    public static string RenderNotes(MeetingDocument d, DateTimeOffset generatedAt)
    {
        var fm = CommonFrontMatter(d, "notes");
        var b = new StringBuilder();
        b.Append("# ").AppendLine(Heading(d.Title)).AppendLine();
        CopyBanner(b, d);
        b.AppendLine("## Meeting Information").AppendLine();
        b.AppendLine($"- **Date:** {DateLine(d)}");
        AppendProjectLines(b, d);
        if (!string.IsNullOrWhiteSpace(d.OwnerName ?? d.OwnerEmail)) b.AppendLine($"- **Owner:** {Inline(d.OwnerName ?? d.OwnerEmail!)}");
        if (d.Attendees.Count > 0) b.AppendLine($"- **Participants:** {Inline(string.Join(", ", d.Attendees.Select(Person)))}");
        if (!string.IsNullOrWhiteSpace(d.CalendarTitle) && d.CalendarTitle != d.Title) b.AppendLine($"- **Calendar event:** {Inline(d.CalendarTitle!)}");
        if (!string.IsNullOrWhiteSpace(d.SourceUrl)) b.AppendLine($"- **Source:** [Open in {SourceName(d.Source)}]({d.SourceUrl})");
        if (d.TranscriptLink is not null) b.AppendLine($"- **Transcript:** [{Inline(d.Title)} — Transcript](<{d.TranscriptLink}>)");
        b.AppendLine();

        if (!string.IsNullOrWhiteSpace(d.NotesMarkdown))
        {
            b.AppendLine("## Meeting Notes").AppendLine();
            b.AppendLine("<!-- Written by the note owner in Granola. -->").AppendLine();
            b.AppendLine(NormalizeNewlines(d.NotesMarkdown!).Trim()).AppendLine();
        }
        if (!string.IsNullOrWhiteSpace(d.SummaryMarkdown))
        {
            if (d.Source == MeetingSource.Fireflies)
            {
                b.AppendLine("## AI Notes").AppendLine();
                b.AppendLine("<!-- Generated by Fireflies.ai. Stored verbatim from the Fireflies API. -->").AppendLine();
            }
            else
            {
                b.AppendLine("## Summary").AppendLine();
                b.AppendLine("<!-- Generated by Granola. Stored verbatim from the Granola API. -->").AppendLine();
            }
            b.AppendLine(DemoteHeadings(NormalizeNewlines(d.SummaryMarkdown!).Trim())).AppendLine();
        }
        if (string.IsNullOrWhiteSpace(d.NotesMarkdown) && string.IsNullOrWhiteSpace(d.SummaryMarkdown))
        {
            b.AppendLine(d.Source == MeetingSource.Fireflies
                ? "_Fireflies has not produced AI notes for this call yet. They are added on a later sync._"
                : "_Granola returned no notes or summary for this meeting._").AppendLine();
        }
        if (d.IncludeAttachmentLinks && d.Attachments.Count > 0)
        {
            b.AppendLine("## Attachments").AppendLine();
            b.AppendLine("<!-- Attachment URLs come from Granola, may expire, and grant access to anyone holding them. -->");
            foreach (var a in d.Attachments.Where(a => !string.IsNullOrWhiteSpace(a.Url)))
                b.AppendLine($"- [{Inline(a.Type ?? "attachment")} {a.Id}]({a.Url})");
            b.AppendLine();
        }
        return Assemble(fm, b.ToString(), generatedAt);
    }

    public static string RenderTranscript(MeetingDocument d, DateTimeOffset generatedAt)
    {
        var fm = CommonFrontMatter(d, "transcript");
        fm.Add(("transcript_segments", d.Transcript.Count.ToString(CultureInfo.InvariantCulture)));
        var b = new StringBuilder();
        b.Append("# ").Append(Heading(d.Title)).AppendLine(" — Transcript").AppendLine();
        CopyBanner(b, d);
        b.AppendLine($"**Meeting Date:** {DateLine(d)}").AppendLine();
        if (d.ProjectName is not null) b.AppendLine($"**Project:** {Inline(d.ProjectName)}").AppendLine();
        if (d.NotesLink is not null) b.AppendLine($"**Notes:** [{Inline(d.Title)}](<{d.NotesLink}>)").AppendLine();
        if (d.Source == MeetingSource.Fireflies)
        {
            b.AppendLine("> Speaker names are as Fireflies.ai recorded them; anonymous labels such as \"Speaker 1\" are local");
            b.AppendLine("> to this transcript.").AppendLine();
        }
        else
        {
            b.AppendLine("> Speaker names appear only where Granola identified the speaker. Other labels are taken from the");
            b.AppendLine("> source as-is; anonymous labels such as \"Speaker A\" are local to this transcript.").AppendLine();
        }
        b.AppendLine("## Transcript").AppendLine();

        var first = d.Transcript.Select(s => s.StartTime).FirstOrDefault(t => t.HasValue);
        string? currentLabel = null;
        var paragraph = new List<string>();
        void Flush()
        {
            if (paragraph.Count == 0) return;
            b.AppendLine(string.Join(" ", paragraph)).AppendLine();
            paragraph.Clear();
        }
        foreach (var seg in d.Transcript)
        {
            var label = SpeakerLabel(seg.Speaker, d.OwnerName);
            if (label != currentLabel)
            {
                Flush();
                var ts = seg.StartTime.HasValue && first.HasValue ? $"[{Offset(seg.StartTime.Value - first.Value)}] " : "";
                b.AppendLine($"**{ts}{Inline(label)}:**").AppendLine();
                currentLabel = label;
            }
            var text = EscapeTranscriptText(seg.Text);
            if (text.Length > 0) paragraph.Add(text);
        }
        Flush();
        return Assemble(fm, b.ToString(), generatedAt);
    }

    public static string SpeakerLabel(GranolaSpeaker? s, string? ownerName)
    {
        if (s is null) return "Unknown speaker";
        if (!string.IsNullOrWhiteSpace(s.Name)) return s.Name.Trim();
        if (!string.IsNullOrWhiteSpace(s.DiarizationLabel)) return s.DiarizationLabel.Trim();
        return s.Attribution switch
        {
            "me" => string.IsNullOrWhiteSpace(ownerName) ? "Me (note owner)" : $"{ownerName.Trim()} (note owner)",
            "them" => "Other participant",
            _ => s.Source switch
            {
                "microphone" => "Unknown speaker (microphone)",
                "speaker" => "Unknown speaker (system audio)",
                _ => "Unknown speaker",
            },
        };
    }

    // ---------- document hashing ----------

    [GeneratedRegex(@"^(generated_at|content_hash): .*\n", RegexOptions.Multiline)]
    private static partial Regex VolatileLines();

    /// <summary>Hash of the document ignoring <c>generated_at</c> and <c>content_hash</c> lines and line-ending differences.</summary>
    public static string ComputeHash(string document)
    {
        var text = NormalizeNewlines(document);
        var end = FrontMatterEnd(text);
        if (end > 0) text = VolatileLines().Replace(text[..end], "") + text[end..];
        return "sha256:" + Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(text)));
    }

    /// <summary>Reads the front matter of an existing file. Returns null if the file has none.</summary>
    public static Dictionary<string, string>? ReadFrontMatter(string document)
    {
        var text = NormalizeNewlines(document);
        var end = FrontMatterEnd(text);
        if (end <= 0) return null;
        var dict = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var line in text[4..end].Split('\n'))
        {
            var idx = line.IndexOf(": ", StringComparison.Ordinal);
            if (idx <= 0 || line.StartsWith(' ')) continue;
            var value = line[(idx + 2)..].Trim();
            if (value.Length >= 2 && value[0] == '"' && value[^1] == '"')
            {
                try { value = System.Text.Json.JsonSerializer.Deserialize<string>(value) ?? value; } catch { /* keep raw */ }
            }
            dict[line[..idx]] = value;
        }
        return dict;
    }

    /// <summary>True when the file still matches the hash recorded inside it (i.e. not edited by a user).</summary>
    public static bool IsUnmodified(string document)
    {
        var fm = ReadFrontMatter(document);
        return fm is not null && fm.TryGetValue("content_hash", out var recorded) && recorded == ComputeHash(document);
    }

    private static int FrontMatterEnd(string text)
    {
        if (!text.StartsWith("---\n", StringComparison.Ordinal)) return -1;
        var idx = text.IndexOf("\n---\n", 3, StringComparison.Ordinal);
        return idx < 0 ? -1 : idx + 5;
    }

    // ---------- helpers ----------

    private static string Assemble(List<(string Key, string Value)> fm, string body, DateTimeOffset generatedAt)
    {
        var core = new StringBuilder("---\n");
        foreach (var (k, v) in fm) core.Append(k).Append(": ").Append(v).Append('\n');
        core.Append("---\n");
        var withoutVolatile = core + body;
        var hash = ComputeHash(withoutVolatile);
        var full = new StringBuilder("---\n");
        foreach (var (k, v) in fm) full.Append(k).Append(": ").Append(v).Append('\n');
        full.Append("generated_at: ").Append(Q(generatedAt.UtcDateTime.ToString("yyyy-MM-ddTHH:mm:ssZ", CultureInfo.InvariantCulture))).Append('\n');
        full.Append("content_hash: ").Append(Q(hash)).Append('\n');
        full.Append("---\n").Append(body);
        return NormalizeNewlines(full.ToString());
    }

    private static List<(string, string)> CommonFrontMatter(MeetingDocument d, string contentType)
    {
        var list = new List<(string, string)>
        {
            ("source", d.Source == MeetingSource.Fireflies ? "fireflies" : "granola"),
            ("content_type", contentType),
            (IdKey(d.Source), Q(d.GranolaNoteId)),
            ("title", Q(d.Title)),
            ("meeting_date", Q(d.MeetingDate.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture))),
        };
        if (d.MeetingStart is { } s) list.Add(("meeting_start", Q(Iso(s))));
        if (d.MeetingEnd is { } e) list.Add(("meeting_end", Q(Iso(e))));
        list.Add(("source_created_at", Q(Iso(d.CreatedAt))));
        list.Add(("source_updated_at", Q(Iso(d.UpdatedAt))));
        list.Add(("project", d.ProjectName is null ? "null" : Q(d.ProjectName)));
        if (d.ProjectSlug is not null) list.Add(("project_slug", Q(d.ProjectSlug)));
        if (d.ProjectId is { } pid) list.Add(("project_id", Q(pid.ToString())));
        if (d.ClientName is not null) list.Add(("client", Q(d.ClientName)));
        list.Add(("location", Q(d.Location.ToString())));
        list.Add(("classification_status", Q(d.ClassificationStatus.ToString())));
        list.Add(("classification_method", Q(d.ClassificationMethod.ToString())));
        if (!string.IsNullOrWhiteSpace(d.ClassificationRule)) list.Add(("classification_rule", Q(d.ClassificationRule!)));
        list.Add(("participants", "[" + string.Join(", ", d.Attendees.Select(a => Q(a.Name ?? a.Email ?? ""))) + "]"));
        if (!string.IsNullOrWhiteSpace(d.SourceUrl)) list.Add(("source_url", Q(d.SourceUrl!)));
        list.Add(("export_role", d.Role == ExportRole.Primary ? "primary" : "copy"));
        if (d.CanonicalProject is not null) list.Add(("canonical_project", Q(d.CanonicalProject)));
        return list;
    }

    /// <summary>The front-matter key that holds the source's meeting ID; used to recognise our own files.</summary>
    public static string IdKey(MeetingSource source) => source == MeetingSource.Fireflies ? "fireflies_transcript_id" : "granola_note_id";

    public static string SourceName(MeetingSource source) => source == MeetingSource.Fireflies ? "Fireflies" : "Granola";

    private static void AppendProjectLines(StringBuilder b, MeetingDocument d)
    {
        var project = d.Location switch
        {
            ExportLocation.Shared => "Shared",
            ExportLocation.Unassigned => d.ClassificationStatus == ClassificationStatus.NeedsReview ? "Unassigned (needs review)" : "Unassigned",
            _ => d.ProjectName ?? "Unassigned",
        };
        b.AppendLine($"- **Project:** {Inline(project)}");
        if (d.ClientName is not null) b.AppendLine($"- **Client:** {Inline(d.ClientName)}");
    }

    private static void CopyBanner(StringBuilder b, MeetingDocument d)
    {
        if (d.Role == ExportRole.Copy)
            b.AppendLine($"> This meeting concerns several projects. This is a copy; the canonical export lives in project '{Inline(d.CanonicalProject ?? "")}'.").AppendLine();
    }

    private static string DateLine(MeetingDocument d)
    {
        if (d.MeetingStart is { } s)
        {
            var end = d.MeetingEnd is { } e ? $" – {e.UtcDateTime:HH:mm}" : "";
            return $"{s.UtcDateTime:yyyy-MM-dd HH:mm}{end} UTC";
        }
        return d.MeetingDate.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture);
    }

    private static string Person(ParticipantFact p) =>
        p.Name is { Length: > 0 } n && p.Email is { Length: > 0 } e ? $"{n} ({e})" : p.Name ?? p.Email ?? "";

    private static string Iso(DateTimeOffset d) => d.UtcDateTime.ToString("yyyy-MM-ddTHH:mm:ssZ", CultureInfo.InvariantCulture);

    private static string Offset(TimeSpan t)
    {
        if (t < TimeSpan.Zero) t = TimeSpan.Zero;
        return $"{(int)t.TotalHours:00}:{t.Minutes:00}:{t.Seconds:00}";
    }

    /// <summary>YAML double-quoted scalar (JSON string syntax is valid YAML).</summary>
    public static string Q(string value) => System.Text.Json.JsonSerializer.Serialize(value, JsonOpts);

    private static readonly System.Text.Json.JsonSerializerOptions JsonOpts = new()
    {
        Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
    };

    public static string NormalizeNewlines(string s) => s.Replace("\r\n", "\n").Replace('\r', '\n');

    private static string Heading(string s) => Inline(string.IsNullOrWhiteSpace(s) ? "Untitled meeting" : s);

    /// <summary>Single-line inline text with HTML-significant characters neutralised.</summary>
    private static string Inline(string s) =>
        NormalizeNewlines(s).Replace('\n', ' ').Replace("<", "\\<").Replace(">", "\\>").Trim();

    [GeneratedRegex(@"^(#{1,5}) ", RegexOptions.Multiline)]
    private static partial Regex HeadingLine();

    /// <summary>Granola summaries use top-level headings; nest them under our "## Summary".</summary>
    private static string DemoteHeadings(string md) => HeadingLine().Replace(md, m => m.Groups[1].Value + "# ");

    [GeneratedRegex(@"^(\s*)([#>+\-*=]|\d+[.)])")]
    private static partial Regex BlockStart();

    /// <summary>
    /// Transcript text is plain speech. Escape only what Markdown would otherwise reinterpret
    /// (HTML tags and block markers at line start) so the wording renders exactly as spoken.
    /// </summary>
    public static string EscapeTranscriptText(string? text)
    {
        if (string.IsNullOrWhiteSpace(text)) return "";
        var lines = NormalizeNewlines(text).Trim().Split('\n')
            .Select(l => BlockStart().Replace(l.Replace("<", "\\<").Replace(">", "\\>"), m =>
            {
                var marker = m.Groups[2].Value;
                // "3." -> "3\." ; "#" -> "\#"
                var escaped = char.IsDigit(marker[0]) ? marker[..^1] + "\\" + marker[^1] : "\\" + marker;
                return m.Groups[1].Value + escaped;
            }));
        return string.Join("  \n", lines);
    }
}
